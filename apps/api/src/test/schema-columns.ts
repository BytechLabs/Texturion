/**
 * Column checks against the generated schema snapshot (#750).
 *
 * Production returned two 500s from queries naming a column the database does
 * not have (`profiles.email`, `task_map_rows.number`), and every route test
 * passed because the fakes accepted any column. This is the one place that
 * knows how to read a PostgREST `select` string and say which names the schema
 * lacks. It serves the fakes (supabaseStub, FakeRest) and the scan of every
 * select the Worker's source builds (api-selects-match-schema.test.ts).
 */
import snapshot from "./schema-snapshot.json";

export interface SchemaSnapshot {
  /** computed: single-argument functions over the row type, which PostgREST serves as columns on read. */
  tables: Record<
    string,
    { kind: "table" | "view"; columns: string[]; computed: string[] }
  >;
  foreignKeys: {
    name: string;
    table: string;
    columns: string[];
    refTable: string;
  }[];
}

/** Generated by scripts/api-schema-snapshot.mjs from the migrated database. */
export const SCHEMA_SNAPSHOT = snapshot as SchemaSnapshot;

export interface Problem {
  table: string;
  column: string;
  reason: string;
}

type SelectItem =
  | { kind: "column"; name: string }
  | { kind: "embed"; name: string; hints: string[]; children: SelectItem[] };

const AGGREGATES = new Set(["count", "sum", "avg", "max", "min"]);
const JOIN_WORDS = new Set(["inner", "left", "right", "full"]);

function splitTopLevel(text: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === "(") depth++;
    else if (ch === ")") depth--;
    else if (ch === "," && depth === 0) {
      parts.push(text.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(text.slice(start));
  return parts.map((p) => p.trim()).filter((p) => p !== "");
}

/** `alias:name` -> `name`. A `::cast` colon is not an alias colon. */
function stripAlias(text: string): string {
  const match = /^[^:()!]+:(?!:)/.exec(text);
  return match ? text.slice(match[0].length) : text;
}

export function parseSelect(select: string): SelectItem[] {
  return splitTopLevel(select).map((raw): SelectItem => {
    const open = raw.indexOf("(");
    if (open !== -1 && raw.endsWith(")")) {
      const head = stripAlias(raw.slice(0, open).trim());
      const inner = raw.slice(open + 1, -1);
      const [name, ...hints] = head.split("!");
      if (inner.trim() === "" && AGGREGATES.has(name)) {
        return { kind: "column", name: "*" };
      }
      return {
        kind: "embed",
        name,
        hints: hints.filter((h) => !JOIN_WORDS.has(h)),
        children: parseSelect(inner),
      };
    }
    let name = stripAlias(raw);
    name = name.split("::")[0];
    name = name.split("->")[0];
    name = name.replace(/\.(sum|avg|max|min|count)\(\)$/, "");
    return { kind: "column", name: name.trim() };
  });
}

function hasColumn(
  schema: SchemaSnapshot,
  table: string,
  column: string,
  forWrite = false,
): boolean {
  const entry = schema.tables[table];
  if (!entry) return false;
  return (
    entry.columns.includes(column) ||
    (!forWrite && entry.computed.includes(column))
  );
}

/**
 * A filter or order name: `col`, `col->json`, or `relation.col` for a column
 * of an embedded table. Returns the problem, if any.
 */
export function checkFilterName(
  name: string,
  table: string,
  schema: SchemaSnapshot = SCHEMA_SNAPSHOT,
): Problem | undefined {
  const parts = name.split("->")[0].split(".");
  let current = table;
  for (const relation of parts.slice(0, -1)) {
    const target = embedTarget(schema, current, relation);
    // An alias from the select list cannot be resolved here; the select
    // itself is checked separately.
    if (!target) return undefined;
    current = target;
  }
  const column = parts[parts.length - 1];
  return hasColumn(schema, current, column)
    ? undefined
    : { table: current, column, reason: `${current} has no column ${column}` };
}

/** Target table of an embed named `name` under `parent`, or undefined. */
function embedTarget(
  schema: SchemaSnapshot,
  parent: string,
  name: string,
): string | undefined {
  if (schema.tables[name]) return name;
  const viaColumn = schema.foreignKeys.find(
    (fk) =>
      fk.table === parent && fk.columns.length === 1 && fk.columns[0] === name,
  );
  if (viaColumn) return viaColumn.refTable;
  return schema.foreignKeys.find((fk) => fk.table === parent && fk.name === name)
    ?.refTable;
}

function relatedByForeignKey(
  schema: SchemaSnapshot,
  a: string,
  b: string,
): boolean {
  if (a === b) return true;
  const direct = schema.foreignKeys.some(
    (fk) =>
      (fk.table === a && fk.refTable === b) ||
      (fk.table === b && fk.refTable === a),
  );
  if (direct) return true;
  // Many-to-many through a junction table that points at both.
  return schema.foreignKeys.some(
    (x) =>
      x.refTable === a &&
      schema.foreignKeys.some((y) => y.table === x.table && y.refTable === b),
  );
}

/**
 * Names in `select` that `table` (or an embedded table) lacks. A relation
 * counts as unknown when it resolves to no table, or when two real tables have
 * no foreign key between them (PostgREST answers PGRST200 for that).
 */
export function checkSelect(
  select: string,
  table: string,
  schema: SchemaSnapshot = SCHEMA_SNAPSHOT,
): Problem[] {
  const problems: Problem[] = [];
  if (!schema.tables[table]) {
    return [{ table, column: "*", reason: `no table or view named ${table}` }];
  }

  function walk(items: SelectItem[], current: string): void {
    for (const item of items) {
      if (item.kind === "column") {
        if (item.name !== "*" && !hasColumn(schema, current, item.name)) {
          problems.push({
            table: current,
            column: item.name,
            reason: `${current} has no column ${item.name}`,
          });
        }
        continue;
      }
      const target = embedTarget(schema, current, item.name);
      if (!target) {
        problems.push({
          table: current,
          column: item.name,
          reason: `${item.name} is not a table, view or foreign-key column reachable from ${current}`,
        });
        continue;
      }
      if (
        schema.tables[current].kind === "table" &&
        !relatedByForeignKey(schema, current, target)
      ) {
        problems.push({
          table: current,
          column: item.name,
          reason: `no foreign key between ${current} and ${target}, so PostgREST cannot embed it`,
        });
      }
      walk(item.children, target);
    }
  }

  walk(parseSelect(select), table);
  return problems;
}

/** `col.desc.nullslast` -> `col`; `rel.col.asc` -> `rel.col`. */
function orderColumn(part: string): string {
  const words = part.split(".");
  while (
    words.length > 1 &&
    ["asc", "desc", "nullsfirst", "nullslast"].includes(words[words.length - 1])
  ) {
    words.pop();
  }
  return words.join(".");
}

const RESERVED_PARAMS = new Set([
  "select",
  "order",
  "limit",
  "offset",
  "on_conflict",
  "columns",
  "or",
  "and",
]);

/**
 * The columns inside an `or=(a.is.null,b.lt.5)` / `and=(...)` value, nested
 * groups included. Operators and values after the first dot are not names.
 */
export function checkLogicalExpression(
  expression: string,
  table: string,
  schema: SchemaSnapshot = SCHEMA_SNAPSHOT,
): Problem[] {
  const problems: Problem[] = [];
  const inner = expression.trim().replace(/^\(/, "").replace(/\)$/, "");
  for (const condition of splitTopLevel(inner)) {
    const group = /^(?:not\.)?(?:and|or)\((.*)\)$/.exec(condition);
    if (group) {
      problems.push(...checkLogicalExpression(group[1], table, schema));
      continue;
    }
    const problem = checkFilterName(condition.split(".")[0], table, schema);
    if (problem) problems.push({ ...problem, reason: `${problem.reason} (or/and)` });
  }
  return problems;
}

/**
 * Everything a PostgREST request names that must exist: the select list,
 * filter columns, order columns, and the keys of an insert/update body.
 * Returns the problems; empty means every name exists.
 */
export function checkRestRequest(
  method: string,
  table: string,
  url: URL,
  body: unknown,
  schema: SchemaSnapshot = SCHEMA_SNAPSHOT,
): Problem[] {
  if (!schema.tables[table]) {
    return [{ table, column: "*", reason: `no table or view named ${table}` }];
  }
  const problems: Problem[] = [];
  const select = url.searchParams.get("select");
  if (select) problems.push(...checkSelect(select, table, schema));
  const miss = (column: string, where: string): void => {
    if (!hasColumn(schema, table, column, where === "write")) {
      problems.push({
        table,
        column,
        reason: `${table} has no column ${column} (${where})`,
      });
    }
  };
  const missPath = (name: string, where: string): void => {
    const problem = checkFilterName(name, table, schema);
    if (problem) problems.push({ ...problem, reason: `${problem.reason} (${where})` });
  };
  for (const [key, value] of url.searchParams.entries()) {
    const last = key.split(".").pop() ?? key;
    if (key === "or" || key === "and") {
      problems.push(...checkLogicalExpression(value, table, schema));
    } else if (!RESERVED_PARAMS.has(last)) {
      missPath(key, "filter");
    }
  }
  const order = url.searchParams.get("order");
  if (order) {
    for (const part of order.split(",")) {
      missPath(orderColumn(part), "order");
    }
  }
  const onConflict = url.searchParams.get("on_conflict");
  if (onConflict) {
    for (const column of onConflict.split(",")) miss(column, "on_conflict");
  }
  if (
    (method === "POST" || method === "PATCH") &&
    body &&
    typeof body === "object"
  ) {
    const keys = new Set<string>();
    for (const row of Array.isArray(body) ? body : [body]) {
      if (row && typeof row === "object") {
        for (const key of Object.keys(row)) keys.add(key);
      }
    }
    for (const key of keys) miss(key, "write");
  }
  return problems;
}

/**
 * The answer PostgREST gives (400, 42703, the message production logged) when
 * a request names a column the schema lacks; undefined when it is fine. The
 * detail is also printed, because the product code under test usually turns
 * the 400 into a generic 500 and the test then fails on a status alone.
 */
export function schemaViolationResponse(
  method: string,
  url: URL,
  body: unknown,
): Response | undefined {
  const match = /^\/rest\/v1\/([A-Za-z0-9_]+)$/.exec(url.pathname);
  if (!match) return undefined;
  const problems = checkRestRequest(method, match[1], url, body);
  if (problems.length === 0) return undefined;
  const message = problems
    .map((p) => `${p.table}.${p.column}: ${p.reason}`)
    .join("; ");
  console.error(
    `[schema snapshot, #750] ${method} ${url.pathname}${url.search} names what the database lacks: ${message}`,
  );
  return Response.json(
    { code: "42703", message: `column does not exist: ${message}` },
    { status: 400 },
  );
}
