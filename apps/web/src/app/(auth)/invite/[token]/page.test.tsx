// @vitest-environment happy-dom
import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import InviteAcceptPage from "./page";

const { accept, fetchMe, updateName, updateUser } = vi.hoisted(() => ({
  accept: vi.fn(),
  fetchMe: vi.fn(),
  updateName: vi.fn(),
  updateUser: vi.fn(),
}));

vi.mock("next/navigation", () => ({
  useParams: () => ({ token: "invite-id" }),
  useRouter: () => ({ push: vi.fn(), replace: vi.fn(), refresh: vi.fn() }),
}));
vi.mock("@/lib/api/me", () => ({
  fetchMe,
  useUpdateDisplayName: () => ({ mutateAsync: updateName }),
}));
vi.mock("@/lib/api/team", () => ({ useAcceptInvite: () => ({ mutate: accept }) }));
vi.mock("@/lib/supabase/browser", () => ({
  getSupabaseBrowser: () => ({
    auth: {
      getSession: async () => ({ data: { session: {} } }),
      onAuthStateChange: () => ({ data: { subscription: { unsubscribe: vi.fn() } } }),
      updateUser,
    },
  }),
}));

beforeEach(() => {
  vi.clearAllMocks();
  updateUser.mockResolvedValue({ error: null });
  window.history.replaceState(null, "", "/invite/invite-id");
});

afterEach(cleanup);

describe("invite acceptance", () => {
  it("lets verified invitees replace the password generated by Supabase", async () => {
    window.history.replaceState(null, "", "/invite/invite-id?setup=password");
    fetchMe.mockResolvedValue({ display_name: "", has_password: true });
    render(<InviteAcceptPage />);

    const password = await screen.findByLabelText("Choose a password");
    expect(accept).not.toHaveBeenCalled();
    fireEvent.change(screen.getByLabelText("Your name"), { target: { value: "Alex" } });
    fireEvent.change(password, { target: { value: "test-password" } });
    fireEvent.click(screen.getByRole("button", { name: "Continue" }));

    await waitFor(() => expect(accept).toHaveBeenCalledOnce());
    expect(updateName).toHaveBeenCalledExactlyOnceWith("Alex");
    expect(updateUser).toHaveBeenCalledExactlyOnceWith({ password: "test-password" });
    expect(updateUser.mock.invocationCallOrder[0]).toBeLessThan(accept.mock.invocationCallOrder[0]);
    expect(window.location.search).toBe("");
  });

  it("accepts an existing account with a name and password directly", async () => {
    fetchMe.mockResolvedValue({ display_name: "Alex", has_password: true });
    render(<InviteAcceptPage />);

    await waitFor(() => expect(accept).toHaveBeenCalledOnce());
    expect(updateUser).not.toHaveBeenCalled();
  });
});
