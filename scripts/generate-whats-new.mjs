#!/usr/bin/env node
/**
 * #756: What's new is written once, in packages/shared/whats-new.json, and this
 * writes it out for each client: the shared list the web reads, the web's
 * catalogue section, and Android's and iOS's list and strings. Before, one entry
 * meant six hand edits and the phones' copies were "checked by eye", which is
 * how the list went three months without a line.
 *
 *   node scripts/generate-whats-new.mjs           write every file
 *   node scripts/generate-whats-new.mjs --check   fail if any file is stale (CI)
 *
 * It also refuses copy that breaks #321's rules: a future date, a dash, a
 * missing language, or a title or body too long to read at a glance.
 */
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "packages/shared/whats-new.json";
/** #321: a list nobody scrolls; the clients show the newest this many. */
const SHOWN = 12;
const TITLE_MAX = 60;
const BODY_MAX = 220;
const HEADER = "Generated by scripts/generate-whats-new.mjs from packages/shared/whats-new.json. Do not edit.";

const OUT = {
  shared: "packages/shared/src/whats-new-entries.ts",
  web: "apps/web/src/i18n/sections/whatsNew.ts",
  androidStrings: "apps/android/app/src/main/kotlin/com/loonext/android/core/i18n/WhatsNewStrings.kt",
  androidEntries: "apps/android/app/src/main/kotlin/com/loonext/android/features/settings/WhatsNewEntries.kt",
  iosStrings: "apps/ios/Loonext/Core/I18n/WhatsNewStrings.swift",
  iosEntries: "apps/ios/Loonext/Features/Settings/WhatsNewEntries.swift",
};

function problemsIn(data) {
  const problems = [];
  const ids = new Set();
  const today = new Date().toISOString().slice(0, 10);
  let previous = "9999-12-31";
  for (const entry of data.entries) {
    const at = `entry ${entry.id ?? "(no id)"}`;
    if (!/^[a-z][A-Za-z0-9]*$/.test(entry.id ?? "")) problems.push(`${at}: the id must be camelCase letters and digits`);
    if (ids.has(entry.id)) problems.push(`${at}: the id is used twice`);
    ids.add(entry.id);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(entry.date ?? "")) problems.push(`${at}: the date must be YYYY-MM-DD`);
    if (entry.date > today) problems.push(`${at}: dated ${entry.date}, after today; entries report what shipped`);
    if (entry.date > previous) problems.push(`${at}: out of order; the list is newest first`);
    previous = entry.date;
    if (entry.href !== null && !/^\//.test(entry.href ?? "")) problems.push(`${at}: href is an in-app path or null`);
    for (const lang of ["en", "fr"]) {
      const copy = entry[lang];
      if (!copy?.title || !copy?.body) {
        problems.push(`${at}: ${lang} needs a title and a body`);
        continue;
      }
      if (copy.title.length > TITLE_MAX) problems.push(`${at}: ${lang} title is over ${TITLE_MAX} characters`);
      if (copy.body.length > BODY_MAX) problems.push(`${at}: ${lang} body is over ${BODY_MAX} characters`);
      if (/[–—]/.test(copy.title + copy.body)) problems.push(`${at}: ${lang} uses a dash`);
    }
    const english = `${entry.en?.title ?? ""} ${entry.en?.body ?? ""}`.toLowerCase();
    if (/coming soon|we will|we'll be|soon you|\broadmap\b|\bplanned\b|\bin beta\b/.test(english)) {
      problems.push(`${at}: announces something that has not shipped`);
    }
  }
  for (const quiet of data.quietReleases ?? []) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(quiet.date ?? "") || !(quiet.reason ?? "").trim()) {
      problems.push("a quiet release needs a YYYY-MM-DD date and a reason");
    }
  }
  return problems;
}

const key = (entry, part) => `${entry.id}${part}`;
const kotlin = (text) => `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$")}"`;
const swift = (text) => `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const ts = (text) => JSON.stringify(text);

function render(shown) {
  const pairs = (lang) =>
    shown.flatMap((entry) => [
      [key(entry, "Title"), entry[lang].title],
      [key(entry, "Body"), entry[lang].body],
    ]);
  const files = {};

  files.shared = `// ${HEADER}
import type { WhatsNewEntry } from "./whats-new";

export const WHATS_NEW_ENTRIES: WhatsNewEntry[] = [
${shown
  .map(
    (entry) =>
      `  {\n    date: ${ts(entry.date)},\n    title: ${ts(`whatsNew.${key(entry, "Title")}`)},\n` +
      `    body: ${ts(`whatsNew.${key(entry, "Body")}`)},\n    href: ${entry.href === null ? "null" : ts(entry.href)},\n  },`,
  )
  .join("\n")}
];
`;

  files.web = `// ${HEADER}
import type { Translated } from "../translated";

export const whatsNewEn = {
${pairs("en").map(([name, text]) => `  ${name}: ${ts(text)},`).join("\n")}
};

export const whatsNewFr: Translated<typeof whatsNewEn> = {
${pairs("fr").map(([name, text]) => `  ${name}: ${ts(text)},`).join("\n")}
};
`;

  files.androidStrings = `// ${HEADER}
package com.loonext.android.core.i18n

object WhatsNewStrings : AppStrings.Section {
    override val en = mapOf(
${pairs("en").map(([name, text]) => `        "whatsNew.${name}" to ${kotlin(text)},`).join("\n")}
    )

    override val frCA = mapOf(
${pairs("fr").map(([name, text]) => `        "whatsNew.${name}" to ${kotlin(text)},`).join("\n")}
    )
}
`;

  files.androidEntries = `// ${HEADER}
package com.loonext.android.features.settings

/** Newest first, the newest ${SHOWN}. */
val WHATS_NEW_ENTRIES: List<WhatsNewEntry> = listOf(
${shown
  .map((entry) => `    WhatsNewEntry(${kotlin(entry.date)}, ${kotlin(`whatsNew.${key(entry, "Title")}`)}, ${kotlin(`whatsNew.${key(entry, "Body")}`)}),`)
  .join("\n")}
)
`;

  files.iosStrings = `// ${HEADER}
enum WhatsNewStrings {
    static let section = AppStrings.Section(
        name: "WhatsNewStrings",
        en: [
${pairs("en").map(([name, text]) => `            "whatsNew.${name}": ${swift(text)},`).join("\n")}
        ],
        frCA: [
${pairs("fr").map(([name, text]) => `            "whatsNew.${name}": ${swift(text)},`).join("\n")}
        ]
    )
}
`;

  files.iosEntries = `// ${HEADER}
/// Newest first, the newest ${SHOWN}.
let whatsNewGeneratedEntries: [WhatsNewEntry] = [
${shown
  .map(
    (entry) =>
      `    WhatsNewEntry(\n        date: ${swift(entry.date)},\n        title: ${swift(`whatsNew.${key(entry, "Title")}`)},\n` +
      `        body: ${swift(`whatsNew.${key(entry, "Body")}`)}\n    ),`,
  )
  .join("\n")}
]
`;
  return files;
}

const data = JSON.parse(readFileSync(SOURCE, "utf8"));
const problems = problemsIn(data);
if (problems.length > 0) {
  console.error(`${SOURCE} has problems:\n${problems.map((p) => `  - ${p}`).join("\n")}`);
  process.exit(1);
}

const files = render(data.entries.slice(0, SHOWN));
const check = process.argv.includes("--check");
const stale = [];
for (const [name, body] of Object.entries(files)) {
  const path = OUT[name];
  if (check) {
    let current = "";
    try {
      current = readFileSync(path, "utf8").replace(/\r\n/g, "\n");
    } catch {
      // A missing file is stale.
    }
    if (current !== body) stale.push(path);
  } else {
    writeFileSync(path, body);
  }
}
if (check && stale.length > 0) {
  console.error(
    `What's new is out of step with ${SOURCE}:\n${stale.map((p) => `  - ${p}`).join("\n")}\n` +
      "Run: node scripts/generate-whats-new.mjs",
  );
  process.exit(1);
}
console.log(
  check
    ? `What's new: every client matches ${SOURCE} (${data.entries.length} entries, newest ${Math.min(SHOWN, data.entries.length)} shown).`
    : `What's new: wrote ${Object.keys(files).length} files from ${SOURCE}.`,
);
